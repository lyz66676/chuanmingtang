// 排除酒类和茶叶，展示亲民知名的零食和调味品
export const featuredProducts: Product[] = (() => {
  const badgeProducts = products.filter((p) => (p.badge === "热销" || p.badge === "特惠") && p.parentCategory !== "wine" && p.parentCategory !== "tea");
  if (badgeProducts.length >= 8) return badgeProducts.slice(0, 16);
  const seen = new Set(badgeProducts.map((p) => p.id));
  const sorted = [...products].filter((p) => !seen.has(p.id) && p.parentCategory !== "wine" && p.parentCategory !== "tea").sort((a, b) => (b.sales || 0) - (a.sales || 0));
  return [...badgeProducts, ...sorted].slice(0, 16);
})();
